-- Tablas nuevas de IAYO: conversaciones, mensajes y estado del modelo.
create table if not exists public.iayo_conversations (
  id uuid primary key default gen_random_uuid(),
  title text not null default 'Nueva conversación',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.iayo_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.iayo_conversations(id) on delete cascade,
  role text not null check (role in ('user','assistant','system')),
  content text not null,
  created_at timestamptz not null default now()
);
create table if not exists public.iayo_model_state (
  id integer primary key default 1 check (id = 1),
  model_name text not null default 'IAYO',
  model_version text not null default '1.0.0',
  state jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
